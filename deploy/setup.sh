#!/usr/bin/env bash
# Radio Net server setup: LiveKit + Radio Net API + Caddy (auto-HTTPS) on one Ubuntu 24.04 VPS.
# Run as root ON THE VPS from the uploaded source dir (deploy.sh does this for you):
#   sudo bash /opt/radionet-src/deploy/setup.sh
# Idempotent: safe to re-run after code changes. Secrets are generated once and kept in /etc/radionet.
#
# Optional env overrides:
#   PUBLIC_IP=1.2.3.4        skip auto-detection
#   API_HOST=api.5by5.app  LK_HOST=voice.5by5.app
#   Unset both to use radio-<ip-with-dashes>.sslip.io and lk-<ip-with-dashes>.sslip.io.
#   On 5by5.app, the Cloudflare A records must be DNS only (grey cloud): Caddy uses HTTP-01.
#   ACME_EMAIL=you@example.com  (Let's Encrypt expiry notices; also enables ZeroSSL fallback)
#   RENDER_ONLY=/tmp/out     write config files there and exit (used for local testing)
set -euo pipefail

LIVEKIT_VERSION="${LIVEKIT_VERSION:-1.13.9}"
CADDY_VERSION="${CADDY_VERSION:-2.11.7}"
NODE_VERSION="${NODE_VERSION:-24.21.0}"
PROMETHEUS_VERSION="${PROMETHEUS_VERSION:-3.15.0}"
NODE_EXPORTER_VERSION="${NODE_EXPORTER_VERSION:-1.12.1}"
# SHA-256 of the linux/amd64 archives for the versions above. Change the hash when the version changes.
NODE_SHA256="${NODE_SHA256:-fd8e59d5a511510f6a298afb548f18c7d2b1be404d8b4a27d94fbe49f56cb2d6}"
LIVEKIT_SHA256="${LIVEKIT_SHA256:-0b7fa208b662d09cfdeae8c06cf4c481aead0556086558b48250501e2e2d6e20}"
CADDY_SHA256="${CADDY_SHA256:-727b91701a392de6ebc5027509f548bf39979e5216340d0faed8fa5e69c84f8b}"
PROMETHEUS_SHA256="${PROMETHEUS_SHA256:-2a542df32eac02ee17b9d844fb2aa1de00dafa5476579ba8a3ba862e9d572ea0}"
NODE_EXPORTER_SHA256="${NODE_EXPORTER_SHA256:-b51d8a76aa2a9156a55d501aca6276fae09e262259a5e4e831d2c2222f084e63}"

fetch_verified() {
  local url="$1" sha="$2" archive="$3"
  curl -fsSL "$url" -o "$archive"
  echo "${sha}  ${archive}" | sha256sum -c -
}

SRC_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"   # contains deploy/ and server/
APP_DIR=/opt/radionet
ETC_DIR=/etc/radionet
RENDER_ONLY="${RENDER_ONLY:-}"

log() { printf '\n== %s\n' "$*"; }

# ---------- public IP + hostnames ----------
detect_ip() {
  local ip
  ip="$(curl -4 -fsS --max-time 5 https://api.ipify.org 2>/dev/null || true)"
  if [[ ! "$ip" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    ip="$(ip -4 route get 1.1.1.1 | awk '{for(i=1;i<NF;i++) if($i=="src"){print $(i+1); exit}}')"
  fi
  printf '%s' "$ip"
}
PUBLIC_IP="${PUBLIC_IP:-$(detect_ip)}"
[[ "$PUBLIC_IP" =~ ^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo "Could not detect public IPv4; set PUBLIC_IP=" >&2; exit 1; }
DASHED="${PUBLIC_IP//./-}"
API_HOST="${API_HOST:-radio-${DASHED}.sslip.io}"
LK_HOST="${LK_HOST:-lk-${DASHED}.sslip.io}"
# Hostnames are interpolated into the Caddyfile. Reject anything that is not a DNS name.
if [[ ! "$API_HOST" =~ ^[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?$ || "$API_HOST" == *..* || ! "$LK_HOST" =~ ^[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?$ || "$LK_HOST" == *..* ]]; then
  echo "API_HOST and LK_HOST must be hostnames (API_HOST=$API_HOST LK_HOST=$LK_HOST)." >&2
  exit 1
fi

# ---------- secrets (generated once) ----------
rand() { head -c "$1" /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c "$2"; }
SECRETS_FILE="${RENDER_ONLY:+$RENDER_ONLY/secrets.env}"
SECRETS_FILE="${SECRETS_FILE:-$ETC_DIR/secrets.env}"
mkdir -p "$(dirname "$SECRETS_FILE")"
if [[ ! -s "$SECRETS_FILE" ]]; then
  umask 077
  cat > "$SECRETS_FILE" <<SECRETS
LIVEKIT_API_KEY=API$(rand 32 12)
LIVEKIT_API_SECRET=$(rand 96 48)
COMMUNITY_SETUP_CODE=$(rand 32 4)-$(rand 32 4)-$(rand 32 4)
RN_STORE_MAC_KEY=$(rand 96 48)
SECRETS
  umask 022
fi
if ! grep -q '^RN_STORE_MAC_KEY=' "$SECRETS_FILE"; then
  umask 077
  echo "RN_STORE_MAC_KEY=$(rand 96 48)" >> "$SECRETS_FILE"
  umask 022
fi
# Monitor basic-auth password, and the LiveKit /metrics password. Both stay off the public internet.
for key in MONITOR_PASSWORD METRICS_PASSWORD; do
  if ! grep -q "^${key}=" "$SECRETS_FILE"; then
    umask 077
    echo "${key}=$(rand 48 24)" >> "$SECRETS_FILE"
    umask 022
  fi
done
# shellcheck disable=SC1090
source "$SECRETS_FILE"

# Caddy basic_auth wants a bcrypt hash. The full install hashes after Caddy is on disk.
hash_password() {
  local pass="$1" bin=""
  if [[ -x "$APP_DIR/bin/caddy" ]]; then bin="$APP_DIR/bin/caddy"
  elif command -v caddy >/dev/null 2>&1; then bin="$(command -v caddy)"
  else return 1
  fi
  "$bin" hash-password --plaintext "$pass"
}
prepare_monitor_hash() {
  MONITOR_HASH="$(hash_password "$MONITOR_PASSWORD" || true)"
}

# ---------- config files ----------
render_configs() {
  local out="$1"
  mkdir -p "$out"
  cat > "$out/livekit.yaml" <<YAML
# LiveKit server config (generated by setup.sh). Signal (7880) is only reachable through Caddy on 443.
port: 7880
bind_addresses:
  - 127.0.0.1
rtc:
  tcp_port: 7881          # ICE/TCP fallback for networks that block UDP
  udp_port: 7882          # all media multiplexed on one UDP port (simple firewall)
  use_external_ip: true
keys:
  ${LIVEKIT_API_KEY}: ${LIVEKIT_API_SECRET}
room:
  empty_timeout: 300
  # One milsim net can be the whole group. 50 was too low for a 60-person op.
  max_participants: 100
logging:
  level: info
  pion_level: warn
# /metrics is HTTP with a password. UFW does not allow port 6789; Prometheus scrapes localhost.
prometheus:
  port: 6789
  username: metrics
  password: ${METRICS_PASSWORD}
YAML

  # The bcrypt hash contains $. A placeholder is replaced after the file is written
  # so the heredoc does not expand it.
  local monitor_site
  if [[ -n "${MONITOR_HASH:-}" ]]; then
    monitor_site="$(cat <<MONITOR
	redir /monitor /monitor/ 308
	@monitor_query path /monitor/prom/api/v1/query /monitor/prom/api/v1/query_range
	handle @monitor_query {
		basic_auth {
			operator __MONITOR_HASH__
		}
		uri strip_prefix /monitor/prom
		reverse_proxy 127.0.0.1:9090
	}
	handle_path /monitor/* {
		basic_auth {
			operator __MONITOR_HASH__
		}
		header X-Robots-Tag "noindex"
		header X-Content-Type-Options "nosniff"
		header Referrer-Policy "no-referrer"
		header Content-Security-Policy "default-src 'self'; connect-src 'self'; style-src 'self'; script-src 'self'; img-src 'none'; object-src 'none'; base-uri 'self'; frame-ancestors 'none'; form-action 'none'"
		root * ${APP_DIR}/monitor
		file_server
	}
MONITOR
)"
  else
    monitor_site="$(cat <<'MONITOR'
	handle /monitor /monitor/* {
		respond "Monitor is not configured" 403
	}
MONITOR
)"
  fi

  cat > "$out/prometheus.yml" <<PROM
global:
  scrape_interval: 15s
  scrape_timeout: 10s
scrape_configs:
  - job_name: livekit
    metrics_path: /metrics
    basic_auth:
      username: metrics
      password: ${METRICS_PASSWORD}
    static_configs:
      - targets: ['127.0.0.1:6789']
  - job_name: node
    static_configs:
      - targets: ['127.0.0.1:9100']
PROM

  cat > "$out/Caddyfile" <<CADDY
# Caddy reverse proxy with automatic HTTPS (generated by setup.sh).
{
${ACME_EMAIL:+	email ${ACME_EMAIL}}
	# UFW allows TCP 443 only. HTTP/3 is QUIC on UDP 443, and clients that try it stall.
	servers {
		protocols h1 h2
	}
	log {
		output file /var/log/caddy/access.log {
			roll_size 10mb
			roll_keep 5
			roll_keep_for 168h
		}
		# Drop request headers so Authorization and X-Admin-Key never land in the access log.
		format filter {
			wrap json
			fields {
				request>headers delete
			}
		}
	}
}

${API_HOST} {
	encode gzip
	header Strict-Transport-Security "max-age=31536000"

	# Browser UI preview: static, fully mocked build (no API or LiveKit calls; CSP blocks any fetch/WebSocket).
	redir /preview /preview/ 308
	handle_path /preview/* {
		root * ${APP_DIR}/preview
		header Content-Security-Policy "default-src 'self'; connect-src 'none'; img-src 'self' data:; style-src 'self' 'unsafe-inline'; frame-ancestors 'none'"
		header X-Robots-Tag "noindex"
		file_server
	}

${monitor_site}

	handle {
		reverse_proxy 127.0.0.1:8787
	}
}

${LK_HOST} {
	reverse_proxy 127.0.0.1:7880
}
CADDY

  cat > "$out/api.env" <<ENV
# Radio Net API environment (generated by setup.sh)
NODE_ENV=production
HOST=127.0.0.1
PORT=8787
SEED_DEV=0
# Caddy is the only proxy. The join limit must see the client IP, not 127.0.0.1 for everyone.
TRUST_PROXY=1
JOIN_RATE_LIMIT=60
# Token refresh is per channel. A squad behind one NAT can exceed the old default of 120.
GLOBAL_RATE_LIMIT=600
RN_DIAGNOSTICS_DIR=/var/lib/radionet/diagnostics
LIVEKIT_URL=wss://${LK_HOST}
LIVEKIT_HTTP_URL=http://127.0.0.1:7880
RN_DATA_FILE=/var/lib/radionet/store.json
ENV

  if [[ -n "${MONITOR_HASH:-}" ]]; then
    local hashed
    hashed="$(mktemp)"
    awk -v h="$MONITOR_HASH" '{gsub(/__MONITOR_HASH__/, h)}1' "$out/Caddyfile" > "$hashed"
    mv "$hashed" "$out/Caddyfile"
  fi
}

if [[ -n "$RENDER_ONLY" ]]; then
  prepare_monitor_hash
  render_configs "$RENDER_ONLY"
  echo "Rendered to $RENDER_ONLY (API_HOST=$API_HOST LK_HOST=$LK_HOST)"
  exit 0
fi

[[ $EUID -eq 0 ]] || { echo "Run as root (sudo)." >&2; exit 1; }
[[ -d "$SRC_DIR/server/src" ]] || { echo "Expected server source at $SRC_DIR/server" >&2; exit 1; }

log "Packages"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq curl ca-certificates ufw rsync xz-utils unattended-upgrades fail2ban >/dev/null

log "User and directories"
id radionet >/dev/null 2>&1 || useradd --system --home "$APP_DIR" --shell /usr/sbin/nologin radionet
mkdir -p "$APP_DIR/bin" "$APP_DIR/server" "$APP_DIR/monitor" "$ETC_DIR" /var/lib/caddy /var/lib/radionet /var/lib/radionet/diagnostics /var/lib/radionet/prometheus /var/lib/radionet/bundles /var/log/caddy /var/log/journal
chown radionet:radionet /var/lib/radionet /var/lib/radionet/diagnostics /var/lib/radionet/prometheus /var/lib/radionet/bundles /var/log/caddy
chmod 750 /var/log/caddy /var/lib/radionet /var/lib/radionet/diagnostics /var/lib/radionet/prometheus /var/lib/radionet/bundles
chmod 750 "$ETC_DIR"; chgrp radionet "$ETC_DIR"; chmod 640 "$SECRETS_FILE"; chgrp radionet "$SECRETS_FILE"
# A restore extracts store.json as root, before this user exists. The API runs as radionet and must be able to rewrite it.
if [[ -f /var/lib/radionet/store.json ]]; then
  chown radionet:radionet /var/lib/radionet/store.json
  chmod 600 /var/lib/radionet/store.json
fi

log "Node.js v$NODE_VERSION"
if [[ "$("$APP_DIR/node/bin/node" -v 2>/dev/null || true)" != "v$NODE_VERSION" ]]; then
  rm -rf "$APP_DIR/node" && mkdir -p "$APP_DIR/node"
  archive="$(mktemp)"
  fetch_verified "https://nodejs.org/dist/v${NODE_VERSION}/node-v${NODE_VERSION}-linux-x64.tar.xz" "$NODE_SHA256" "$archive"
  tar xJ -C "$APP_DIR/node" --strip-components=1 -f "$archive"
  rm -f "$archive"
fi

log "LiveKit v$LIVEKIT_VERSION"
if ! "$APP_DIR/bin/livekit-server" --version 2>/dev/null | grep -q "$LIVEKIT_VERSION"; then
  archive="$(mktemp)"
  fetch_verified "https://github.com/livekit/livekit/releases/download/v${LIVEKIT_VERSION}/livekit_${LIVEKIT_VERSION}_linux_amd64.tar.gz" "$LIVEKIT_SHA256" "$archive"
  tar xz -C "$APP_DIR/bin" -f "$archive" livekit-server
  rm -f "$archive"
fi

log "Caddy v$CADDY_VERSION"
if ! "$APP_DIR/bin/caddy" version 2>/dev/null | grep -q "v$CADDY_VERSION"; then
  archive="$(mktemp)"
  fetch_verified "https://github.com/caddyserver/caddy/releases/download/v${CADDY_VERSION}/caddy_${CADDY_VERSION}_linux_amd64.tar.gz" "$CADDY_SHA256" "$archive"
  tar xz -C "$APP_DIR/bin" -f "$archive" caddy
  rm -f "$archive"
fi
setcap 'cap_net_bind_service=+ep' "$APP_DIR/bin/caddy"

log "Prometheus v$PROMETHEUS_VERSION"
if ! "$APP_DIR/bin/prometheus" --version 2>/dev/null | grep -q "version ${PROMETHEUS_VERSION}"; then
  archive="$(mktemp)"
  fetch_verified "https://github.com/prometheus/prometheus/releases/download/v${PROMETHEUS_VERSION}/prometheus-${PROMETHEUS_VERSION}.linux-amd64.tar.gz" "$PROMETHEUS_SHA256" "$archive"
  tar xz -C "$APP_DIR/bin" --strip-components=1 -f "$archive" "prometheus-${PROMETHEUS_VERSION}.linux-amd64/prometheus"
  rm -f "$archive"
fi

log "node_exporter v$NODE_EXPORTER_VERSION"
if ! "$APP_DIR/bin/node_exporter" --version 2>/dev/null | grep -q "version ${NODE_EXPORTER_VERSION}"; then
  archive="$(mktemp)"
  fetch_verified "https://github.com/prometheus/node_exporter/releases/download/v${NODE_EXPORTER_VERSION}/node_exporter-${NODE_EXPORTER_VERSION}.linux-amd64.tar.gz" "$NODE_EXPORTER_SHA256" "$archive"
  tar xz -C "$APP_DIR/bin" --strip-components=1 -f "$archive" "node_exporter-${NODE_EXPORTER_VERSION}.linux-amd64/node_exporter"
  rm -f "$archive"
fi

log "Radio Net API"
rsync -a --delete --exclude node_modules --exclude '*.log' "$SRC_DIR/server/" "$APP_DIR/server/"
(cd "$APP_DIR/server" && PATH="$APP_DIR/node/bin:$PATH" npm ci --no-audit --no-fund --loglevel=error)

log "Browser UI preview (optional)"
if [[ -f "$SRC_DIR/preview/index.html" ]]; then
  mkdir -p "$APP_DIR/preview"
  rsync -a --delete "$SRC_DIR/preview/" "$APP_DIR/preview/"
  echo "Preview installed: https://${API_HOST}/preview/"
else
  echo "No preview build in $SRC_DIR/preview; /preview/ will 404 (run pack.sh with PREVIEW_DIST set)."
fi
log "Monitor dashboard"
if [[ -d "$SRC_DIR/deploy/monitor" ]]; then
  rsync -a --delete "$SRC_DIR/deploy/monitor/" "$APP_DIR/monitor/"
else
  echo "No monitor files at $SRC_DIR/deploy/monitor" >&2
  exit 1
fi
chown -R radionet:radionet "$APP_DIR" /var/lib/caddy

log "Configs"
prepare_monitor_hash
[[ -n "$MONITOR_HASH" ]] || { echo "Could not hash the monitor password (Caddy binary missing)." >&2; exit 1; }
render_configs "$ETC_DIR"
chgrp radionet "$ETC_DIR"/*; chmod 640 "$ETC_DIR"/*

log "systemd units"
install -m 644 "$SRC_DIR/deploy/systemd/"*.service /etc/systemd/system/
install -m 755 "$SRC_DIR/deploy/collect-scale-logs.sh" /usr/local/sbin/radionet-collect-logs
systemctl daemon-reload
systemctl enable --now livekit.service radionet-api.service radionet-caddy.service prometheus.service node_exporter.service
systemctl restart livekit.service radionet-api.service radionet-caddy.service prometheus.service node_exporter.service

log "Persistent journal"
mkdir -p /etc/systemd/journald.conf.d /var/log/journal
systemd-tmpfiles --create --prefix /var/log/journal >/dev/null 2>&1 || true
cat > /etc/systemd/journald.conf.d/radionet.conf <<'EOF'
[Journal]
Storage=persistent
Compress=yes
SystemMaxUse=200M
RuntimeMaxUse=50M
MaxRetentionSec=7day
MaxFileSec=1day
EOF
systemctl restart systemd-journald

log "SSH, unattended upgrades, fail2ban"
install -d -m 755 /etc/ssh/sshd_config.d
# 00- sorts before Vultr's 50-cloud-init.conf. sshd keeps the first value it reads,
# so a later 99-radionet.conf cannot turn PasswordAuthentication off.
rm -f /etc/ssh/sshd_config.d/99-radionet.conf
cat > /etc/ssh/sshd_config.d/00-radionet.conf <<'EOF'
PasswordAuthentication no
KbdInteractiveAuthentication no
PermitRootLogin prohibit-password
EOF
if systemctl is-active --quiet ssh; then systemctl reload ssh
elif systemctl is-active --quiet sshd; then systemctl reload sshd
fi
cat > /etc/apt/apt.conf.d/20auto-upgrades <<'EOF'
APT::Periodic::Update-Package-Lists "1";
APT::Periodic::Unattended-Upgrade "1";
EOF
systemctl enable --now unattended-upgrades
cat > /etc/fail2ban/jail.d/radionet.local <<'EOF'
[sshd]
enabled = true
port = ssh
maxretry = 5
findtime = 10m
bantime = 1h
EOF
systemctl enable --now fail2ban
systemctl restart fail2ban

log "Firewall"
ufw default deny incoming >/dev/null
ufw default allow outgoing >/dev/null
ufw allow 22/tcp   comment 'ssh' >/dev/null
ufw allow 80/tcp   comment 'http (ACME + redirect)' >/dev/null
ufw allow 443/tcp  comment 'https: API + LiveKit signalling' >/dev/null
# UDP 443 stays closed. Caddy is configured for h1 and h2 only, so clients do not try QUIC.
ufw allow 7881/tcp comment 'LiveKit ICE/TCP' >/dev/null
ufw allow 7882/udp comment 'LiveKit media (UDP mux)' >/dev/null
ufw --force enable >/dev/null

log "Health checks"
ok=1
for _ in $(seq 1 30); do curl -fsS http://127.0.0.1:8787/health >/dev/null 2>&1 && break; sleep 1; done
curl -fsS http://127.0.0.1:8787/health >/dev/null || { echo "API not healthy: journalctl -u radionet-api"; ok=0; }
curl -fsS http://127.0.0.1:7880/ >/dev/null || { echo "LiveKit not healthy: journalctl -u livekit"; ok=0; }
for _ in $(seq 1 20); do curl -fsS -u "metrics:${METRICS_PASSWORD}" http://127.0.0.1:6789/metrics >/dev/null 2>&1 && break; sleep 1; done
curl -fsS -u "metrics:${METRICS_PASSWORD}" http://127.0.0.1:6789/metrics >/dev/null || { echo "LiveKit metrics not ready (port 6789 is localhost only)"; ok=0; }
curl -fsS http://127.0.0.1:9100/metrics >/dev/null || { echo "node_exporter not ready: journalctl -u node_exporter"; ok=0; }
for _ in $(seq 1 20); do curl -fsS http://127.0.0.1:9090/-/ready >/dev/null 2>&1 && break; sleep 1; done
curl -fsS http://127.0.0.1:9090/-/ready >/dev/null || { echo "Prometheus not ready: journalctl -u prometheus"; ok=0; }
for _ in $(seq 1 60); do curl -fsS "https://${API_HOST}/health" >/dev/null 2>&1 && break; sleep 2; done
curl -fsS "https://${API_HOST}/health" >/dev/null || { echo "HTTPS not ready yet (cert issuance?): journalctl -u radionet-caddy"; ok=0; }

cat <<DONE

==========================================================
 Radio Net server $( ((ok)) && echo READY || echo 'needs attention (see above)')
 API (put in the client as VITE_API_URL): https://${API_HOST}
 LiveKit (handed to clients by the API):  wss://${LK_HOST}
 UI preview (mocked, if packed):           https://${API_HOST}/preview/
 Community setup code (keep private):     ${COMMUNITY_SETUP_CODE:0:4}-****-**** (full value in ${SECRETS_FILE})
 Secrets: ${SECRETS_FILE}
 Monitor (basic auth, not public): https://${API_HOST}/monitor/
 Monitor user: operator
 Monitor password: MONITOR_PASSWORD in ${SECRETS_FILE} (not printed here)
 Logs:    journalctl -u livekit -u radionet-api -u radionet-caddy -u prometheus -f
          Caddy access log (JSON, rotated): /var/log/caddy/access.log
          Journal storage: persistent, 200 MB, 7 days
          After the op: radionet-collect-logs 6
 HTTP/3:  off (firewall allows TCP 443 only)
 Metrics: LiveKit :6789 and Prometheus :9090 stay on localhost. UFW does not open them.
==========================================================
DONE
